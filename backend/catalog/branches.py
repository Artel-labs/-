from dataclasses import dataclass


@dataclass(frozen=True)
class Branch:
    title: str
    fragments: tuple[str, ...]


BRANCHES = (
    Branch(
        "Гражданское и договорное право",
        ("гражданского права", "договорного права", "контрактное право", "составления договоров"),
    ),
    Branch("Корпоративное право", ("корпоративное право",)),
    Branch("Интеллектуальная собственность", ("интеллектуальная собственность", "авторское право")),
    Branch("Цифровое право", ("цифровое право", "цифровых инструментов", "нейроправо")),
    Branch(
        "Международное и зарубежное право",
        (
            "международное частное право",
            "правовую систему китая",
            "французское (европейское) экономическое право",
            "контрактное право гонконга",
            "английское контрактное право",
            "морской арбитраж",
        ),
    ),
    Branch("Налоговое и финансовое право", ("налогового администрирования", "налоговые проверки", "исламские финансы")),
    Branch("Банкротство", ("правовые вопросы банкротства",)),
    Branch("Трудовое право", ("трудовое право", "кадровую работу")),
    Branch("Семейное право", ("имущественные отношения в семье",)),
    Branch(
        "Медицинское и фармацевтическое право",
        ("фармацевтических компаний", "юридическая ответственность врача", "лекарственных препаратов"),
    ),
    Branch("Транспортное право", ("транспортное право", "морской арбитраж")),
)


def branch_titles(program_title: str) -> list[str]:
    lowered = program_title.lower()
    return [branch.title for branch in BRANCHES if any(fragment in lowered for fragment in branch.fragments)]
